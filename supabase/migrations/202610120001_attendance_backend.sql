-- Spa POS - Attendance backend API
-- Additive migration. Attendance is separate from cashier shifts.
-- Real GPS coordinates are required from the browser; timestamps are server-generated.
begin;

create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete restrict,
  attendance_date date not null default ((now() at time zone 'Asia/Ho_Chi_Minh')::date),
  check_in_at timestamptz,
  check_out_at timestamptz,
  check_in_latitude double precision,
  check_in_longitude double precision,
  check_in_accuracy_m double precision,
  check_out_latitude double precision,
  check_out_longitude double precision,
  check_out_accuracy_m double precision,
  check_in_note text,
  check_out_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint attendance_records_one_employee_day unique (employee_id, attendance_date),
  constraint attendance_checkin_pair check (
    (check_in_latitude is null and check_in_longitude is null and check_in_accuracy_m is null)
    or (check_in_latitude between -90 and 90 and check_in_longitude between -180 and 180
        and check_in_accuracy_m is not null and check_in_accuracy_m >= 0)
  ),
  constraint attendance_checkout_pair check (
    (check_out_latitude is null and check_out_longitude is null and check_out_accuracy_m is null)
    or (check_out_latitude between -90 and 90 and check_out_longitude between -180 and 180
        and check_out_accuracy_m is not null and check_out_accuracy_m >= 0)
  ),
  constraint attendance_checkout_requires_checkin check (
    check_out_at is null or (check_in_at is not null and check_out_at >= check_in_at)
  )
);

create index if not exists ix_attendance_date on public.attendance_records(attendance_date desc);
create index if not exists ix_attendance_employee_date on public.attendance_records(employee_id, attendance_date desc);

create table if not exists public.attendance_adjustment_audit (
  id bigint generated by default as identity primary key,
  attendance_id bigint not null references public.attendance_records(id) on delete restrict,
  action text not null check (action in ('CREATE','CHECK_IN','CHECK_OUT','ADJUST')),
  changed_by uuid not null,
  reason text,
  before_data jsonb,
  after_data jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists ix_attendance_audit_record on public.attendance_adjustment_audit(attendance_id, created_at desc);

insert into public.permissions(code, name, description)
values
 ('ATTENDANCE_SELF', 'Chấm công cá nhân', 'Nhân viên tự chấm công vào/ra bằng GPS thật'),
 ('ATTENDANCE_VIEW', 'Xem chấm công', 'Xem dữ liệu chấm công theo phạm vi được phân quyền'),
 ('ATTENDANCE_MANAGE', 'Quản lý chấm công', 'Điều chỉnh chấm công có lý do và lưu nhật ký')
on conflict (code) do nothing;

-- Role assignments use the current role codes. No broad permission is granted to CASHIER/EMPLOYEE.
insert into public.role_permissions(role_id, permission_id)
select r.id, p.id
from public.roles r
join public.permissions p on p.code = 'ATTENDANCE_SELF'
where r.code in ('ADMIN','MANAGER','CASHIER','EMPLOYEE')
on conflict do nothing;

insert into public.role_permissions(role_id, permission_id)
select r.id, p.id
from public.roles r
join public.permissions p on p.code in ('ATTENDANCE_VIEW','ATTENDANCE_MANAGE')
where r.code in ('ADMIN','MANAGER')
on conflict do nothing;

create or replace function public.attendance_current_employee_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select e.id
  from public.employees e
  where e.auth_user_id = auth.uid()
    and coalesce(e.is_active, true) = true
  limit 1;
$$;

revoke all on function public.attendance_current_employee_id() from public;
grant execute on function public.attendance_current_employee_id() to authenticated;

alter table public.attendance_records enable row level security;
alter table public.attendance_adjustment_audit enable row level security;

drop policy if exists attendance_records_select on public.attendance_records;
create policy attendance_records_select on public.attendance_records
for select to authenticated
using (
  (employee_id = public.attendance_current_employee_id()
   and public.has_permission('ATTENDANCE_SELF'))
  or public.has_permission('ATTENDANCE_VIEW')
  or public.has_permission('ATTENDANCE_MANAGE')
);

drop policy if exists attendance_records_no_direct_insert on public.attendance_records;
create policy attendance_records_no_direct_insert on public.attendance_records
for insert to authenticated with check (false);

drop policy if exists attendance_records_no_direct_update on public.attendance_records;
create policy attendance_records_no_direct_update on public.attendance_records
for update to authenticated using (false) with check (false);

drop policy if exists attendance_records_no_direct_delete on public.attendance_records;
create policy attendance_records_no_direct_delete on public.attendance_records
for delete to authenticated using (false);

drop policy if exists attendance_audit_select on public.attendance_adjustment_audit;
create policy attendance_audit_select on public.attendance_adjustment_audit
for select to authenticated
using (
  public.has_permission('ATTENDANCE_VIEW')
  or public.has_permission('ATTENDANCE_MANAGE')
  or exists (
    select 1 from public.attendance_records a
    where a.id = attendance_id
      and a.employee_id = public.attendance_current_employee_id()
      and public.has_permission('ATTENDANCE_SELF')
  )
);

drop policy if exists attendance_audit_no_direct_insert on public.attendance_adjustment_audit;
create policy attendance_audit_no_direct_insert on public.attendance_adjustment_audit
for insert to authenticated with check (false);
drop policy if exists attendance_audit_no_direct_update on public.attendance_adjustment_audit;
create policy attendance_audit_no_direct_update on public.attendance_adjustment_audit
for update to authenticated using (false) with check (false);
drop policy if exists attendance_audit_no_direct_delete on public.attendance_adjustment_audit;
create policy attendance_audit_no_direct_delete on public.attendance_adjustment_audit
for delete to authenticated using (false);

create or replace function public.attendance_punch_in(
  p_latitude double precision,
  p_longitude double precision,
  p_accuracy_m double precision,
  p_note text default null
)
returns public.attendance_records
language plpgsql
security definer
set search_path = public
as $$
declare
  v_employee_id bigint;
  v_date date := (now() at time zone 'Asia/Ho_Chi_Minh')::date;
  v_row public.attendance_records;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED' using errcode = '42501'; end if;
  if not public.has_permission('ATTENDANCE_SELF') then raise exception 'FORBIDDEN: ATTENDANCE_SELF' using errcode = '42501'; end if;
  if p_latitude is null or p_latitude < -90 or p_latitude > 90
     or p_longitude is null or p_longitude < -180 or p_longitude > 180
     or p_accuracy_m is null or p_accuracy_m < 0 then
    raise exception 'INVALID_GPS_DATA' using errcode = '22023';
  end if;

  v_employee_id := public.attendance_current_employee_id();
  if v_employee_id is null then raise exception 'EMPLOYEE_LINK_REQUIRED' using errcode = '42501'; end if;

  perform 1 from public.employees where id = v_employee_id and coalesce(is_active,true) = true;
  if not found then raise exception 'EMPLOYEE_INACTIVE' using errcode = '42501'; end if;

  insert into public.attendance_records(
    employee_id, attendance_date, check_in_at, check_in_latitude,
    check_in_longitude, check_in_accuracy_m, check_in_note
  ) values (
    v_employee_id, v_date, now(), p_latitude, p_longitude, p_accuracy_m, nullif(btrim(p_note),'')
  )
  on conflict (employee_id, attendance_date) do nothing
  returning * into v_row;

  if v_row.id is null then
    raise exception 'ATTENDANCE_ALREADY_EXISTS_TODAY' using errcode = '23505';
  end if;

  insert into public.attendance_adjustment_audit(attendance_id, action, changed_by, after_data)
  values (v_row.id, 'CHECK_IN', auth.uid(), to_jsonb(v_row));
  return v_row;
end;
$$;

create or replace function public.attendance_punch_out(
  p_latitude double precision,
  p_longitude double precision,
  p_accuracy_m double precision,
  p_note text default null
)
returns public.attendance_records
language plpgsql
security definer
set search_path = public
as $$
declare
  v_employee_id bigint;
  v_date date := (now() at time zone 'Asia/Ho_Chi_Minh')::date;
  v_row public.attendance_records;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED' using errcode = '42501'; end if;
  if not public.has_permission('ATTENDANCE_SELF') then raise exception 'FORBIDDEN: ATTENDANCE_SELF' using errcode = '42501'; end if;
  if p_latitude is null or p_latitude < -90 or p_latitude > 90
     or p_longitude is null or p_longitude < -180 or p_longitude > 180
     or p_accuracy_m is null or p_accuracy_m < 0 then
    raise exception 'INVALID_GPS_DATA' using errcode = '22023';
  end if;

  v_employee_id := public.attendance_current_employee_id();
  if v_employee_id is null then raise exception 'EMPLOYEE_LINK_REQUIRED' using errcode = '42501'; end if;

  select * into v_row
  from public.attendance_records
  where employee_id = v_employee_id and attendance_date = v_date
  for update;

  if not found then raise exception 'CHECK_IN_REQUIRED' using errcode = 'P0002'; end if;
  if v_row.check_in_at is null then raise exception 'CHECK_IN_REQUIRED' using errcode = 'P0002'; end if;
  if v_row.check_out_at is not null then raise exception 'ALREADY_CHECKED_OUT' using errcode = '23505'; end if;

  update public.attendance_records
  set check_out_at = now(), check_out_latitude = p_latitude,
      check_out_longitude = p_longitude, check_out_accuracy_m = p_accuracy_m,
      check_out_note = nullif(btrim(p_note),''), updated_at = now()
  where id = v_row.id
  returning * into v_row;

  insert into public.attendance_adjustment_audit(attendance_id, action, changed_by, after_data)
  values (v_row.id, 'CHECK_OUT', auth.uid(), to_jsonb(v_row));
  return v_row;
end;
$$;

create or replace function public.attendance_adjust(
  p_attendance_id bigint,
  p_check_in_at timestamptz,
  p_check_out_at timestamptz,
  p_reason text
)
returns public.attendance_records
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.attendance_records;
  v_before jsonb;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED' using errcode = '42501'; end if;
  if not public.has_permission('ATTENDANCE_MANAGE') then raise exception 'FORBIDDEN: ATTENDANCE_MANAGE' using errcode = '42501'; end if;
  if p_attendance_id is null or p_attendance_id <= 0 then raise exception 'INVALID_ATTENDANCE_ID' using errcode = '22023'; end if;
  if nullif(btrim(p_reason),'') is null then raise exception 'ADJUSTMENT_REASON_REQUIRED' using errcode = '22023'; end if;
  if p_check_in_at is null then raise exception 'CHECK_IN_TIME_REQUIRED' using errcode = '22023'; end if;
  if p_check_out_at is not null and p_check_out_at < p_check_in_at then raise exception 'CHECK_OUT_BEFORE_CHECK_IN' using errcode = '22023'; end if;

  select * into v_row from public.attendance_records where id = p_attendance_id for update;
  if not found then raise exception 'ATTENDANCE_NOT_FOUND' using errcode = 'P0002'; end if;
  v_before := to_jsonb(v_row);

  update public.attendance_records
  set check_in_at = p_check_in_at,
      check_out_at = p_check_out_at,
      updated_at = now()
  where id = p_attendance_id
  returning * into v_row;

  insert into public.attendance_adjustment_audit(
    attendance_id, action, changed_by, reason, before_data, after_data
  ) values (v_row.id, 'ADJUST', auth.uid(), btrim(p_reason), v_before, to_jsonb(v_row));

  return v_row;
end;
$$;

revoke all on function public.attendance_punch_in(double precision,double precision,double precision,text) from public;
revoke all on function public.attendance_punch_out(double precision,double precision,double precision,text) from public;
revoke all on function public.attendance_adjust(bigint,timestamptz,timestamptz,text) from public;
grant execute on function public.attendance_punch_in(double precision,double precision,double precision,text) to authenticated;
grant execute on function public.attendance_punch_out(double precision,double precision,double precision,text) to authenticated;
grant execute on function public.attendance_adjust(bigint,timestamptz,timestamptz,text) to authenticated;

commit;
