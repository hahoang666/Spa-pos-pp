on public.appointments for insert to authenticated
with check (
  created_by = auth.uid()
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.is_active = true
      and p.role_id = any (array[1,2,3]::bigint[])
  )
);

