drop policy if exists "Active profiles can read appointments" on public.appointments;
create policy "Active profiles can read appointments"
on public.appointments for select to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.is_active = true
      and p.role_id = any (array[1,2,3]::bigint[])
  )
);

drop policy if exists "Active profiles can create appointments" on public.appointments;
