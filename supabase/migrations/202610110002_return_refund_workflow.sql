begin;

-- Return/refund workflow v1: additive tables and RPCs.
-- Does not alter create_invoice, create_payment, cancel_invoice, or shift RPCs.
-- A return must be recorded, reversed/adjusted, and only then refunded.
-- No cashbook OUT is created until refund_return() succeeds.

-- 1. Dedicated permissions.
insert into public.permissions (code, name, description)
values
  ('RETURN_VIEW', 'Xem phiếu trả hàng', 'Xem phiếu trả hàng và trạng thái hoàn tiền'),
  ('RETURN_CREATE', 'Tạo phiếu trả hàng', 'Ghi nhận hàng khách trả, chưa chi tiền'),
  ('RETURN_REVERSE', 'Đảo phiếu trả hàng', 'Xác nhận đảo/điều chỉnh phiếu trả hàng'),
  ('RETURN_REFUND', 'Hoàn tiền trả hàng', 'Thực hiện hoàn tiền sau khi đảo phiếu')
on conflict (code) do nothing;

-- View for configured business roles. Creation is limited to cashier/manager/admin;
-- reversal and refund are restricted to manager/admin.
insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
join public.permissions p on p.code = 'RETURN_VIEW'
where r.code in ('ADMIN', 'MANAGER', 'CASHIER', 'EMPLOYEE')
on conflict do nothing;

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
join public.permissions p on p.code = 'RETURN_CREATE'
where r.code in ('ADMIN', 'MANAGER', 'CASHIER')
on conflict do nothing;

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
join public.permissions p on p.code in ('RETURN_REVERSE', 'RETURN_REFUND')
where r.code in ('ADMIN', 'MANAGER')
on conflict do nothing;

-- 2. Return slip header and items. Quantities on pending slips reserve the
-- returned quantity so concurrent/double submissions cannot exceed sold qty.
create table if not exists public.sales_returns (
  id bigint generated by default as identity primary key,
  code text not null unique,
  invoice_id bigint not null references public.invoices(id) on delete restrict,
  status text not null default 'PENDING_REVERSAL'
    check (status in ('PENDING_REVERSAL', 'REVERSED', 'CANCELLED')),
  reason text not null check (length(btrim(reason)) > 0),
  subtotal_before_vat numeric(18,3) not null default 0 check (subtotal_before_vat >= 0),
  discount_amount numeric(18,3) not null default 0 check (discount_amount >= 0),
  vat_amount numeric(18,3) not null default 0 check (vat_amount >= 0),
  total_amount numeric(18,3) not null default 0 check (total_amount >= 0),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  reversed_by uuid references auth.users(id) on delete set null,
  reversed_at timestamptz,
  reversal_reference text,
  reversal_reason text,
  updated_at timestamptz not null default now()
);

create table if not exists public.sales_return_items (
  id bigint generated by default as identity primary key,
  return_id bigint not null references public.sales_returns(id) on delete restrict,
  invoice_item_id bigint not null references public.invoice_items(id) on delete restrict,
  product_id bigint references public.products(id) on delete set null,
  product_code text,
  product_name text,
  quantity numeric(18,3) not null check (quantity > 0),
  unit_price_before_vat numeric(18,3) not null check (unit_price_before_vat >= 0),
  subtotal_before_vat numeric(18,3) not null check (subtotal_before_vat >= 0),
  discount_amount numeric(18,3) not null check (discount_amount >= 0),
  vat_amount numeric(18,3) not null check (vat_amount >= 0),
  total_amount numeric(18,3) not null check (total_amount >= 0),
  created_at timestamptz not null default now(),
  unique (return_id, invoice_item_id)
);

-- Refund attempts are separate from the return slip and are only inserted after reversal.
create table if not exists public.sales_return_refunds (
  id bigint generated by default as identity primary key,
  return_id bigint not null references public.sales_returns(id) on delete restrict,
  payment_method_id bigint not null references public.payment_methods(id) on delete restrict,
  amount numeric(18,3) not null check (amount > 0),
  reference_no text,
  notes text,
  shift_id bigint not null references public.shifts(id) on delete restrict,
  fund_id bigint not null references public.funds(id) on delete restrict,
  created_by uuid references auth.users(id) on delete set null,
  refunded_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists sales_returns_invoice_idx
  on public.sales_returns(invoice_id);
create index if not exists sales_returns_status_idx
  on public.sales_returns(status);
create index if not exists sales_return_items_invoice_item_idx
  on public.sales_return_items(invoice_item_id);
create index if not exists sales_return_refunds_return_idx
  on public.sales_return_refunds(return_id);

-- Expand payment status without changing the existing invoice lifecycle status.
alter table public.invoices
  drop constraint if exists invoices_payment_status_check;
alter table public.invoices
  add constraint invoices_payment_status_check
  check (payment_status = any (array[
    'UNPAID'::text,
    'PARTIALLY_PAID'::text,
    'PAID'::text,
    'CANCELLED'::text,
    'PARTIALLY_REFUNDED'::text,
    'REFUNDED'::text
  ]));

alter table public.sales_returns enable row level security;
alter table public.sales_return_items enable row level security;
alter table public.sales_return_refunds enable row level security;

drop policy if exists "Users with RETURN_VIEW can read sales returns" on public.sales_returns;
create policy "Users with RETURN_VIEW can read sales returns"
  on public.sales_returns for select to authenticated
  using (public.has_permission('RETURN_VIEW'));

drop policy if exists "Users with RETURN_VIEW can read return items" on public.sales_return_items;
create policy "Users with RETURN_VIEW can read return items"
  on public.sales_return_items for select to authenticated
  using (
    public.has_permission('RETURN_VIEW')
    and exists (
      select 1 from public.sales_returns sr
      where sr.id = sales_return_items.return_id
    )
  );

