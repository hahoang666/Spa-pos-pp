  on public.sales_return_refunds for delete to authenticated using (false);

-- 3. Create a return slip. p_items is an array of
-- {"invoice_item_id": <id>, "quantity": <positive numeric>}.
create or replace function public.create_return(
  p_invoice_id bigint,
  p_items jsonb,
  p_reason text
)
returns public.sales_returns
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_user uuid := auth.uid();
  v_invoice public.invoices;
  v_shift public.shifts;
  v_return public.sales_returns;
  v_item_json jsonb;
  v_invoice_item public.invoice_items;
  v_qty numeric(18,3);
  v_subtotal numeric(18,3);
  v_discount numeric(18,3);
  v_vat numeric(18,3);
  v_total numeric(18,3);
  v_returned_qty numeric(18,3);
  v_sum_subtotal numeric(18,3) := 0;
  v_sum_discount numeric(18,3) := 0;
  v_sum_vat numeric(18,3) := 0;
  v_sum_total numeric(18,3) := 0;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;
  if not public.has_permission('RETURN_CREATE') then
    raise exception 'FORBIDDEN: missing permission RETURN_CREATE' using errcode = '42501';
  end if;
  if p_invoice_id is null or p_invoice_id <= 0 then
    raise exception 'INVALID_INVOICE_ID' using errcode = '22023';
  end if;
  if p_reason is null or length(btrim(p_reason)) = 0 then
    raise exception 'RETURN_REASON_REQUIRED' using errcode = '22023';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'RETURN_ITEMS_REQUIRED' using errcode = '22023';
  end if;

  select * into v_shift
  from public.shifts
  where opened_by = v_user and status = 'OPEN'
  order by opened_at desc limit 1
  for update;
  if not found then
    raise exception 'FORBIDDEN: no open shift for current user' using errcode = '42501';
  end if;

  select * into v_invoice
  from public.invoices
  where id = p_invoice_id
  for update;
  if not found then
    raise exception 'INVOICE_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_invoice.status <> 'COMPLETED' then
    raise exception 'INVOICE_NOT_RETURNABLE' using errcode = '22023';
  end if;
  if coalesce(v_invoice.paid_amount, 0) <= 0 then
    raise exception 'INVOICE_HAS_NO_PAID_AMOUNT' using errcode = '22023';
  end if;

  insert into public.sales_returns (
    code, invoice_id, status, reason, created_by
  )
  values (
    'TR-' || to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS') || '-' || substr(gen_random_uuid()::text, 1, 6),
    p_invoice_id, 'PENDING_REVERSAL', btrim(p_reason), v_user
  )
  returning * into v_return;

  for v_item_json in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item_json->>'invoice_item_id', '') !~ '^[0-9]+$' then
      raise exception 'INVALID_INVOICE_ITEM_ID' using errcode = '22023';
    end if;
    begin
      v_qty := (v_item_json->>'quantity')::numeric;
    exception when others then
      raise exception 'INVALID_RETURN_QUANTITY' using errcode = '22023';
    end;
    if v_qty is null or v_qty <= 0 then
      raise exception 'INVALID_RETURN_QUANTITY' using errcode = '22023';
    end if;

    select * into v_invoice_item
    from public.invoice_items
    where id = (v_item_json->>'invoice_item_id')::bigint
      and invoice_id = p_invoice_id
    for update;
    if not found then
      raise exception 'INVOICE_ITEM_NOT_FOUND' using errcode = '22023';
    end if;
    if v_qty > v_invoice_item.quantity then
      raise exception 'RETURN_QUANTITY_EXCEEDS_SOLD' using errcode = '22023';
    end if;

    select coalesce(sum(sri.quantity), 0)
      into v_returned_qty
      from public.sales_return_items sri
      join public.sales_returns sr on sr.id = sri.return_id
     where sri.invoice_item_id = v_invoice_item.id
       and sr.status <> 'CANCELLED';

    if v_returned_qty + v_qty > v_invoice_item.quantity then
      raise exception 'RETURN_QUANTITY_EXCEEDS_REMAINING' using errcode = '22023';
    end if;

    v_subtotal := round(v_invoice_item.line_subtotal_before_vat * v_qty / v_invoice_item.quantity, 3);
    v_discount := round((v_invoice_item.line_discount_amount + v_invoice_item.allocated_order_discount_amount) * v_qty / v_invoice_item.quantity, 3);
    v_vat := round(v_invoice_item.line_vat_amount * v_qty / v_invoice_item.quantity, 3);
    v_total := round(v_invoice_item.line_total_amount * v_qty / v_invoice_item.quantity, 3);

    insert into public.sales_return_items (
      return_id, invoice_item_id, product_id, product_code, product_name,
      quantity, unit_price_before_vat, subtotal_before_vat,
      discount_amount, vat_amount, total_amount
    )
    values (
      v_return.id, v_invoice_item.id, v_invoice_item.product_id,
      v_invoice_item.product_code, v_invoice_item.product_name,
      v_qty, v_invoice_item.unit_price_before_vat, v_subtotal,
      v_discount, v_vat, v_total
    );

    v_sum_subtotal := v_sum_subtotal + v_subtotal;
    v_sum_discount := v_sum_discount + v_discount;
    v_sum_vat := v_sum_vat + v_vat;
    v_sum_total := v_sum_total + v_total;
  end loop;

  if v_sum_total <= 0 then
    raise exception 'RETURN_AMOUNT_INVALID' using errcode = '22023';
  end if;

  -- Reserve only amounts originally paid; do not refund an unpaid portion.
  if (
    select coalesce(sum(sr.total_amount), 0)
    from public.sales_returns sr
    where sr.invoice_id = p_invoice_id and sr.status <> 'CANCELLED'
      and sr.id <> v_return.id
  ) + v_sum_total > v_invoice.paid_amount then
    raise exception 'RETURN_AMOUNT_EXCEEDS_PAID_AMOUNT' using errcode = '22023';
  end if;

  update public.sales_returns
  set subtotal_before_vat = round(v_sum_subtotal, 3),
      discount_amount = round(v_sum_discount, 3),
      vat_amount = round(v_sum_vat, 3),
      total_amount = round(v_sum_total, 3),
      updated_at = now()
  where id = v_return.id
  returning * into v_return;

  return v_return;
end;
$function$;

revoke all on function public.create_return(bigint, jsonb, text) from public;
grant execute on function public.create_return(bigint, jsonb, text) to authenticated;

-- 4. Mark a return as reversed/adjusted. The reference must identify the
-- completed external e-invoice adjustment/replacement when one is required.
create or replace function public.reverse_return(
  p_return_id bigint,
  p_reversal_reference text,
  p_reversal_reason text
)
returns public.sales_returns
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_user uuid := auth.uid();
  v_shift public.shifts;
  v_return public.sales_returns;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;
  if not public.has_permission('RETURN_REVERSE') then
    raise exception 'FORBIDDEN: missing permission RETURN_REVERSE' using errcode = '42501';
  end if;
  if p_return_id is null or p_return_id <= 0 then
    raise exception 'INVALID_RETURN_ID' using errcode = '22023';
  end if;
  if p_reversal_reference is null or length(btrim(p_reversal_reference)) = 0 then
    raise exception 'REVERSAL_REFERENCE_REQUIRED' using errcode = '22023';
  end if;
  if p_reversal_reason is null or length(btrim(p_reversal_reason)) = 0 then
    raise exception 'REVERSAL_REASON_REQUIRED' using errcode = '22023';
  end if;

  select * into v_shift
  from public.shifts
  where opened_by = v_user and status = 'OPEN'
  order by opened_at desc limit 1
  for update;
  if not found then
    raise exception 'FORBIDDEN: no open shift for current user' using errcode = '42501';
  end if;

  select * into v_return
  from public.sales_returns
  where id = p_return_id
  for update;
  if not found then
    raise exception 'RETURN_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_return.status <> 'PENDING_REVERSAL' then
    raise exception 'RETURN_NOT_PENDING_REVERSAL' using errcode = '23505';
  end if;

  update public.sales_returns
  set status = 'REVERSED',
      reversed_by = v_user,
      reversed_at = now(),
      reversal_reference = btrim(p_reversal_reference),
      reversal_reason = btrim(p_reversal_reason),
      updated_at = now()
  where id = v_return.id
  returning * into v_return;

  return v_return;
end;
$function$;

revoke all on function public.reverse_return(bigint, text, text) from public;
grant execute on function public.reverse_return(bigint, text, text) to authenticated;

-- 5. Refund only after reversal. Each refund creates exactly one cashbook OUT
-- row inside the same transaction; row locks serialize concurrent refund calls.
create or replace function public.refund_return(
  p_return_id bigint,
  p_payment_method_id bigint,
  p_amount numeric,
  p_reference_no text default null,
  p_notes text default null
)
returns public.sales_return_refunds
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_user uuid := auth.uid();
  v_return public.sales_returns;
  v_method public.payment_methods;
  v_fund public.funds;
  v_shift public.shifts;
  v_refund public.sales_return_refunds;
  v_refunded numeric(18,3);
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;
  if not public.has_permission('RETURN_REFUND') then
    raise exception 'FORBIDDEN: missing permission RETURN_REFUND' using errcode = '42501';
  end if;
  if p_return_id is null or p_return_id <= 0 then
    raise exception 'INVALID_RETURN_ID' using errcode = '22023';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'INVALID_REFUND_AMOUNT' using errcode = '22023';
  end if;

  select * into v_shift
  from public.shifts
  where opened_by = v_user and status = 'OPEN'
  order by opened_at desc limit 1
  for update;
  if not found then
    raise exception 'FORBIDDEN: no open shift for current user' using errcode = '42501';
  end if;

  select * into v_return
  from public.sales_returns
  where id = p_return_id
  for update;
  if not found then
    raise exception 'RETURN_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_return.status <> 'REVERSED' then
    raise exception 'RETURN_MUST_BE_REVERSED_BEFORE_REFUND' using errcode = '22023';
  end if;

  select coalesce(sum(amount), 0)
    into v_refunded
    from public.sales_return_refunds
   where return_id = v_return.id;

  if v_refunded + p_amount > v_return.total_amount then
    raise exception 'REFUND_AMOUNT_EXCEEDS_REMAINING' using errcode = '22023';
  end if;

  select * into v_method
  from public.payment_methods
  where id = p_payment_method_id and is_active = true;
  if not found then
    raise exception 'PAYMENT_METHOD_NOT_FOUND_OR_INACTIVE' using errcode = '22023';
  end if;

  select * into v_fund
  from public.funds
  where code = v_method.code and is_active = true
  limit 1;
  if not found then
    raise exception 'FUND_NOT_CONFIGURED_FOR_PAYMENT_METHOD' using errcode = '22023';
  end if;

  insert into public.sales_return_refunds (
    return_id, payment_method_id, amount, reference_no, notes,
    shift_id, fund_id, created_by
  )
  values (
    v_return.id, v_method.id, p_amount, nullif(btrim(p_reference_no), ''),
    nullif(btrim(p_notes), ''), v_shift.id, v_fund.id, v_user
  )
  returning * into v_refund;

  insert into public.cashbook_transactions (
    fund_id, shift_id, transaction_type, category, direction, amount,
    reference_type, reference_id, txn_at, created_by, note
  )
  values (
    v_fund.id, v_shift.id, 'RETURN_REFUND', 'RETURN_REFUND', 'OUT', p_amount,
    'RETURN_REFUND', v_refund.id, now(), v_user,
    'Hoàn tiền phiếu trả hàng ' || v_return.code
  );

  -- Keep paid_amount (original collections) intact. Status reflects all cash
  -- actually refunded across every return for this invoice.
  select coalesce(sum(srr.amount), 0)
    into v_refunded
    from public.sales_return_refunds srr
    join public.sales_returns sr on sr.id = srr.return_id
   where sr.invoice_id = v_return.invoice_id;

  update public.invoices i
  set payment_status = case
        when v_refunded >= coalesce(i.paid_amount, 0) then 'REFUNDED'
        else 'PARTIALLY_REFUNDED'
      end,
      updated_at = now()
  where i.id = v_return.invoice_id
    and i.status = 'COMPLETED';

  return v_refund;
end;
$function$;

revoke all on function public.refund_return(bigint, bigint, numeric, text, text) from public;
grant execute on function public.refund_return(bigint, bigint, numeric, text, text) to authenticated;

commit;
